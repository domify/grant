require_relative "coverage"

module Manifest
  PATH = File.join(CoverageGen::ROOT, "port/manifest.yml")
  module_function

  def generated
    CoverageGen.spec_files.map do |file|
      source = file.delete_prefix(CoverageGen::ROOT + "/")
      parsed = CoverageGen.parse_spec(file)
      scoped = parsed.reject { |e| e["status"] == "excluded" }
      relative = source.delete_prefix("crystal-upstream/spec/")
      target = relative.sub(/_spec\.cr$/, "_test.iyi").tr("/", "_")
      target = "delete_test.iyi" if relative == "grant/persistence/delete_spec.cr"
      excluded = scoped.empty? && (parsed.any? || relative.match?(CoverageGen::ADAPTER_FILE))
      entry = {"source" => source, "target" => target,
               "area" => CoverageGen.classify(relative, parsed.map { |e| e["name"] }.join(" ")),
               "examples" => scoped.size, "status" => excluded ? "excluded" : "todo"}
      entry["exclusion_reason"] = CoverageGen::EXCLUDE_REASON if excluded
      entry
    end.sort_by { |e| [CoverageGen::AREAS.index(e["area"]), e["source"]] }
  end

  def load
    YAML.safe_load(File.read(PATH)) || []
  end

  def generate
    existing = File.exist?(PATH) ? load.to_h { |e| [e["source"], e] } : {}
    entries = generated.map do |entry|
      old = existing[entry["source"]]
      if old && entry["status"] != "excluded"
        entry["status"] = old["status"] if %w[todo done].include?(old["status"])
        entry["target"] = old["target"] if old["target"]
        entry["children"] = old["children"] if old["children"]
      end
      entry["status"] = "done" if entry["source"].end_with?("/persistence/delete_spec.cr") && !old
      entry
    end
    File.write(PATH, "# Generated by ruby port/manifest.rb generate. Edit status/target/children only.\n" + entries.to_yaml)
    entries
  end

  def stats(entries)
    CoverageGen::AREAS.each do |area|
      rows = entries.select { |e| e["area"] == area }
      puts "#{area}: files=#{rows.size} in_scope=#{rows.count { |e| e['status'] != 'excluded' }} done=#{rows.count { |e| e['status'] == 'done' }} excluded=#{rows.count { |e| e['status'] == 'excluded' }} examples=#{rows.sum { |e| e['examples'] }}"
    end
  end
end

if $PROGRAM_NAME == __FILE__
  case ARGV.first
  when "generate" then Manifest.stats(Manifest.generate)
  when "stats" then Manifest.stats(Manifest.load)
  else abort "usage: ruby port/manifest.rb generate|stats"
  end
end
